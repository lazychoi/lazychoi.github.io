def fetch_cover(item):
    isbn = item["ISBN"].strip()
    title = item["제목"].strip()
    for q in [isbn, title]:
        if not q:
            continue
        try:
            url = "https://www.yes24.com/Product/Search?domain=ALL&query=" + urllib.parse.quote(q)
            req = urllib.request.Request(url, headers={"User-Agent": "Mozilla/5.0"})
            with urllib.request.urlopen(req, timeout=6) as r:
                html = r.read().decode("utf-8", errors="ignore")
                m = re.search(r"https://image\.yes24\.com/goods/(\d+)/[A-Z]+", html)
                if m:
                    return f"https://image.yes24.com/goods/{m.group(1)}/L"
        except Exception:
            pass
    return f"https://covers.openlibrary.org/b/isbn/{isbn}-M.jpg" if isbn else ""


def parse_pub_date(raw_date):
    m = re.search(r"(\d{4})년\s*(\d{1,2})월\s*(\d{1,2})일", raw_date or "")
    if m:
        return f"{int(m.group(1)):04d}-{int(m.group(2)):02d}-{int(m.group(3)):02d}"
    return (raw_date or "").strip()


def sql_str(val):
    return "'" + str(val).replace("'", "''") + "'"


def main():
    rows = list(csv.DictReader(io.StringIO(CSV_RAW.strip())))
    print(f"[+] 총 {len(rows)}권의 CSV 도서 데이터를 파싱했습니다.")

    print("[+] ISBN 및 제목 기반으로 도서 표지 이미지(cover_url)를 조회하는 중...")
    with concurrent.futures.ThreadPoolExecutor(max_workers=12) as ex:
        covers = list(ex.map(fetch_cover, rows))

    records = []
    for idx, r in enumerate(rows):
        # 우리 DB에 없는 컬럼(부제, 가격, 서가, 쪽수, ISBN)은 제외하고, 등록일을 완독일(completed_date)로 저장
        records.append({
            "id": idx + 1,
            "status": "read",
            "sort_order": idx + 1,
            "title": r["제목"].strip(),
            "author": r["저자"].strip(),
            "publisher": r["출판사"].strip(),
            "pub_date": parse_pub_date(r["출간일"]),
            "cover_url": covers[idx],
            "completed_date": r["등록일"].strip(),
            "rating": float(r["별점"].strip() or 0),
            "toc": "",
            "quotes": [],
            "memo": r["메모"].strip(),
            "created_at": "2026-11-12T14:00:00Z",
            "updated_at": "2026-11-12T14:00:00Z"
        })

    # 1. data/backup-reading_books.json 저장
    os.makedirs(os.path.dirname(BACKUP_JSON_PATH), exist_ok=True)
    with open(BACKUP_JSON_PATH, "w", encoding="utf-8") as f:
        json.dump(records, f, ensure_ascii=False, indent=2)
    print(f"[+] JSON 백업 데이터 저장 완료: {BACKUP_JSON_PATH} ({len(records)}권)")

    # 2. scripts/import_reading_books.sql 생성
    sql_lines = [
        "-- ============================================================",
        "-- 첨부된 81권의 도서 데이터를 reading_books 테이블에 일괄 입력하는 SQL",
        "-- (부제, 가격, 서가, 쪽수, ISBN 컬럼 제외 / 등록일 -> completed_date 완독일로 저장)",
        "-- ============================================================",
        "",
        "INSERT INTO public.reading_books (status, sort_order, title, author, publisher, pub_date, cover_url, completed_date, rating, quotes, memo, memos)",
        "VALUES"
    ]
    val_rows = []
    for rec in records:
        val_rows.append(
            f"  ({sql_str(rec['status'])}, {rec['sort_order']}, {sql_str(rec['title'])}, {sql_str(rec['author'])}, "
            f"{sql_str(rec['publisher'])}, {sql_str(rec['pub_date'])}, "
            f"{sql_str(rec['cover_url'])}, {sql_str(rec['completed_date'])}, {rec['rating']}, "
            f"'[]'::jsonb, {sql_str(rec['memo'])}, '[]'::jsonb)"
        )
    sql_lines.append(",\n".join(val_rows) + ";\n")

    with open(SQL_OUTPUT_PATH, "w", encoding="utf-8") as f:
        f.write("\n".join(sql_lines))
    print(f"[+] SQL 스크립트 생성 완료: {SQL_OUTPUT_PATH}")

    # 3. Supabase REST API로 직접 업로드 시도
    db_payload = [
        {k: v for k, v in rec.items() if k not in ("id", "created_at", "updated_at")}
        for rec in records
    ]
    req = urllib.request.Request(
        f"{SUPABASE_URL}/rest/v1/reading_books",
        data=json.dumps(db_payload).encode("utf-8"),
        headers={
            "apikey": SUPABASE_KEY,
            "Authorization": f"Bearer {SUPABASE_KEY}",
            "Content-Type": "application/json",
            "Prefer": "return=minimal"
        },
        method="POST"
    )
    try:
        with urllib.request.urlopen(req, timeout=15) as resp:
            print(f"[+] Supabase reading_books 테이블 직접 업로드 완료! (HTTP {resp.status})")
    except urllib.error.HTTPError as e:
        err_msg = e.read().decode("utf-8", errors="ignore")
        print(f"[*] 참고: 익명 키 직접 INSERT는 RLS 보안 정책으로 보호 중입니다 ({e.code}).")
        print("    -> books.html 접속 시 관리자 로그인 세션으로 자동 업로드되거나, import_reading_books.sql로 즉시 반영됩니다.")


if __name__ == "__main__":
    main()
