def write_sql_script(entries, sql_path=SQL_OUTPUT_PATH):
    """Generate idempotent Supabase SQL upsert script for OCR pages 3 to 5."""
    lines = [
        "-- OCR pages 3 to 5 batch update/insert for hanja_dict",
        f"-- Total entries: {len(entries)}",
        "INSERT INTO public.hanja_dict (hanja, korean, meaning)",
        "VALUES",
    ]
    value_lines = []
    for korean, hanja, meaning in entries:
        value_lines.append(
            f"  ({sql_escape(hanja)}, {sql_escape(korean)}, {sql_escape(meaning)})"
        )
    lines.append(",\n".join(value_lines))
    lines.append("ON CONFLICT (hanja, korean) DO UPDATE SET")
    lines.append("  meaning = EXCLUDED.meaning,")
    lines.append("  updated_at = NOW();")
    content = "\n".join(lines) + "\n"
    with open(sql_path, "w", encoding="utf-8", newline="\n") as f:
        f.write(content)
    print(f"[SQL] Wrote {len(entries)} upserts to {sql_path}")


