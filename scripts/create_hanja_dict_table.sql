-- Supabase Dashboard > SQL Editor에 복사하여 실행하세요.
-- ============================================================

-- 1. 한자 사전 커스텀/수정 데이터 테이블 생성
CREATE TABLE IF NOT EXISTS public.hanja_dict (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  hanja TEXT NOT NULL,
  korean TEXT NOT NULL,
  meaning TEXT NOT NULL,
  created_at TIMESTAMPTZ DEFAULT timezone('utc'::text, now()) NOT NULL,
  updated_at TIMESTAMPTZ DEFAULT timezone('utc'::text, now()) NOT NULL,
  CONSTRAINT hanja_dict_hanja_korean_unique UNIQUE (hanja, korean)
);

-- 인덱스 생성 (조회 속도 최적화)
CREATE INDEX IF NOT EXISTS idx_hanja_dict_lookup ON public.hanja_dict (hanja, korean);

-- 2. Row Level Security(RLS) 활성화
ALTER TABLE public.hanja_dict ENABLE ROW LEVEL SECURITY;

-- 3. RLS 정책 설정
-- 1) 모든 사용자(익명 포함)가 등록된 뜻 정보를 조회(SELECT)할 수 있음
DROP POLICY IF EXISTS "Allow public read access" ON public.hanja_dict;
CREATE POLICY "Allow public read access"
  ON public.hanja_dict
  FOR SELECT
  USING (true);

-- 2) 로그인된(인증된) 사용자만 새 뜻/한자를 등록(INSERT)할 수 있음
DROP POLICY IF EXISTS "Allow authenticated insert" ON public.hanja_dict;
CREATE POLICY "Allow authenticated insert"
  ON public.hanja_dict
  FOR INSERT
  TO authenticated
  WITH CHECK (true);

-- 3) 로그인된(인증된) 사용자만 뜻을 수정(UPDATE)할 수 있음
DROP POLICY IF EXISTS "Allow authenticated update" ON public.hanja_dict;
CREATE POLICY "Allow authenticated update"
  ON public.hanja_dict
  FOR UPDATE
  TO authenticated
  USING (true)
  WITH CHECK (true);

-- 4) 로그인된(인증된) 사용자만 삭제(DELETE)할 수 있음
DROP POLICY IF EXISTS "Allow authenticated delete" ON public.hanja_dict;
CREATE POLICY "Allow authenticated delete"
  ON public.hanja_dict
  FOR DELETE
  TO authenticated
  USING (true);
