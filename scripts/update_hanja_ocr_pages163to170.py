def update_hanja_txt_files(entries):
    """Route entries by first syllable to the appropriate data/h*.txt file."""
    grouped = {}
    for k, h, m in entries:
        fname = SYLLABLE_TO_FILE.get(k[0])
        if not fname:
            raise ValueError(f"Unmapped initial syllable: {k!r} ({h})")
        grouped.setdefault(fname, []).append((k, h, m))

    for fname in sorted(grouped.keys()):
        fpath = os.path.join(DATA_DIR, fname)
        _update_single_txt_file(fpath, grouped[fname])


def write_sql_script(entries, output_path):
    """Generate a Supabase SQL Editor script using CTE update + insert."""
    now_iso = datetime.now(timezone.utc).isoformat().replace("+00:00", "Z")
    lines = [
        "-- Supabase SQL Editor script: Update Hanja dictionary meanings from OCR Pages 163 to 170",
        f"-- ([人部] 9~11획 偶(續)~傳: {len(entries)} entries)",
        f"-- Generated at {now_iso}",
        "",
        "begin;",
        "",
        "with v(hanja, korean, meaning, updated_at) as (",
        "  values",
    ]
    for i, (k, h, m) in enumerate(entries):
        comma = "," if i < len(entries) - 1 else ""
        lines.append(
            f"    ({sql_escape(h)}, {sql_escape(k)}, {sql_escape(m)}, '{now_iso}'::timestamptz){comma}"
        )
    lines.extend(
        [
            "),",
            "upd as (",
            "  update public.hanja_dict d",
            "     set meaning = v.meaning,",
            "         updated_at = v.updated_at",
            "    from v",
            "   where d.hanja = v.hanja",
            "     and d.korean = v.korean",
            "  returning d.hanja, d.korean",
            ")",
            "insert into public.hanja_dict (hanja, korean, meaning, created_at, updated_at)",
            "select v.hanja, v.korean, v.meaning, v.updated_at, v.updated_at",
            "  from v",
            " where not exists (",
            "   select 1 from public.hanja_dict d",
            "    where d.hanja = v.hanja and d.korean = v.korean",
            " );",
            "",
            "commit;",
            "",
        ]
    )
    with open(output_path, "w", encoding="utf-8") as fp:
        fp.write("\n".join(lines))
    print(f"[{os.path.basename(output_path)}] Generated SQL script for {len(entries)} rows.")


