-- 1. 독서 기록(reading_books) 테이블 생성
CREATE TABLE IF NOT EXISTS public.reading_books (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  status TEXT NOT NULL DEFAULT 'to_read', -- 'to_read' (읽을 책) | 'read' (읽은 책)
  sort_order INTEGER NOT NULL DEFAULT 0,  -- 읽을 책 목록 상하 이동 순서
  title TEXT NOT NULL,                    -- 책이름
  author TEXT DEFAULT '',                 -- 저자
  publisher TEXT DEFAULT '',              -- 출판사
  pub_date TEXT DEFAULT '',               -- 출간일 (YYYY-MM-DD 또는 YYYY)
  pages INTEGER DEFAULT 0,                -- 쪽수
  isbn TEXT DEFAULT '',                   -- ISBN (ISBN-13 / ISBN-10)
  cover_url TEXT DEFAULT '',              -- 책표지이미지 URL
  completed_date TEXT DEFAULT '',         -- 완독일 (YYYY-MM-DD)
  rating NUMERIC(2,1) DEFAULT 0,          -- 별점 (0.0 ~ 5.0)
  quotes JSONB DEFAULT '[]'::jsonb,       -- 문장 수집 배열: [{ id, page, text, note, created_at }]
  memo TEXT DEFAULT '',                   -- 독서 메모 (자유 노트 및 감상평)
  memos JSONB DEFAULT '[]'::jsonb,        -- 개별 독서 메모 배열: [{ id, page, content, created_at }]
  created_at TIMESTAMPTZ DEFAULT timezone('utc'::text, now()) NOT NULL,
  updated_at TIMESTAMPTZ DEFAULT timezone('utc'::text, now()) NOT NULL
);

-- 인덱스 생성 (조회 및 정렬 속도 최적화)
CREATE INDEX IF NOT EXISTS idx_reading_books_status_order ON public.reading_books (status, sort_order);
CREATE INDEX IF NOT EXISTS idx_reading_books_isbn ON public.reading_books (isbn);

-- 2. Row Level Security(RLS) 활성화
ALTER TABLE public.reading_books ENABLE ROW LEVEL SECURITY;

-- 3. RLS 정책 설정
-- 1) 모든 사용자(익명 포함)가 도서 목록을 조회(SELECT)할 수 있음 (백업 스크립트 및 열람 지원)
DROP POLICY IF EXISTS "Allow public read access on reading_books" ON public.reading_books;
CREATE POLICY "Allow public read access on reading_books"
  ON public.reading_books
  FOR SELECT
  USING (true);

-- 2) 로그인된(인증된) 사용자만 도서를 등록(INSERT)할 수 있음
DROP POLICY IF EXISTS "Allow authenticated insert on reading_books" ON public.reading_books;
CREATE POLICY "Allow authenticated insert on reading_books"
  ON public.reading_books
  FOR INSERT
  TO authenticated
  WITH CHECK (true);

-- 3) 로그인된(인증된) 사용자만 도서를 수정(UPDATE)할 수 있음
DROP POLICY IF EXISTS "Allow authenticated update on reading_books" ON public.reading_books;
CREATE POLICY "Allow authenticated update on reading_books"
  ON public.reading_books
  FOR UPDATE
  TO authenticated
  USING (true)
  WITH CHECK (true);

-- 4) 로그인된(인증된) 사용자만 도서를 삭제(DELETE)할 수 있음
DROP POLICY IF EXISTS "Allow authenticated delete on reading_books" ON public.reading_books;
CREATE POLICY "Allow authenticated delete on reading_books"
  ON public.reading_books
  FOR DELETE
  TO authenticated
  USING (true);
