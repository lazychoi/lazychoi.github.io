def _update_single_txt_file(file_path, entries):
    """Update existing entries (deduplicating repeated keys) and insert missing entries in one txt file."""
    with open(file_path, "rb") as fp:
        raw = fp.read()

    is_utf16 = raw.startswith(b"\xff\xfe")
    text = raw[2:].decode("utf-16le") if is_utf16 else raw.decode("utf-8")
    line_sep = "\r\n" if "\r\n" in text else "\n"
    trailing_newline = text.endswith("\n")
    lines = text.splitlines()

    entry_map = {(k, h): m for k, h, m in entries}
    seen_keys = set()
    updated_count = 0
    deduped_count = 0
    new_lines = []

    for line in lines:
        stripped = line.strip()
        if not stripped:
            new_lines.append(line)
            continue
        parts = stripped.split("|", 2)
        if len(parts) >= 2:
            key = (parts[0].strip(), parts[1].strip())
            if key in entry_map:
                if key in seen_keys:
                    deduped_count += 1
                    continue
                seen_keys.add(key)
                new_lines.append(f"{key[0]}|{key[1]}|{entry_map[key]}")
                updated_count += 1
                continue
        new_lines.append(line)

    missing_entries = [(k, h, m) for k, h, m in entries if (k, h) not in seen_keys]
    if missing_entries:
        # Group missing entries by initial syllable so each inserts within its contiguous syllable block.
        by_syl = {}
        for item in missing_entries:
            by_syl.setdefault(item[0][0], []).append(item)

        for syl, syl_items in by_syl.items():
            syl_indices = [
                i for i, l in enumerate(new_lines)
                if l.strip() and l.split("|", 1)[0].strip().startswith(syl)
            ]
            if syl_indices:
                block_start = syl_indices[0]
                block_end = syl_indices[-1]
                for k, h, m in sorted(syl_items, key=lambda x: (x[0], x[1])):
                    insert_idx = block_end + 1
                    for idx in range(block_start, block_end + 1):
                        cur_k = new_lines[idx].split("|", 1)[0].strip() if new_lines[idx].strip() else ""
                        if cur_k > k:
                            insert_idx = idx
                            break
                    new_lines.insert(insert_idx, f"{k}|{h}|{m}")
                    block_end += 1
            else:
                for k, h, m in sorted(syl_items, key=lambda x: (x[0], x[1])):
                    insert_idx = len(new_lines)
                    for idx, l in enumerate(new_lines):
                        cur_k = l.split("|", 1)[0].strip() if l.strip() else ""
                        if cur_k > k:
                            insert_idx = idx
                            break
                    new_lines.insert(insert_idx, f"{k}|{h}|{m}")

    out_text = line_sep.join(new_lines) + (line_sep if trailing_newline else "")
    with open(file_path, "wb") as fp:
        if is_utf16:
            fp.write(b"\xff\xfe" + out_text.encode("utf-16le"))
        else:
            fp.write(out_text.encode("utf-8"))

    print(
        f"[{os.path.basename(file_path)}] Updated: {updated_count}, Deduplicated: {deduped_count}, "
        f"Inserted: {len(missing_entries)}, Total entries handled: {len(entries)}"
    )


def update_hanja_txt_files(entries):
    """Route entries by first syllable to the appropriate data/h*.txt dictionary file."""
    grouped = {}
    for k, h, m in entries:
        fname = SYLLABLE_TO_FILE[k[0]]
        grouped.setdefault(fname, []).append((k, h, m))

    for fname in sorted(grouped.keys()):
        _update_single_txt_file(os.path.join(DATA_DIR, fname), grouped[fname])


