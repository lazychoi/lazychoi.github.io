-- 1. 추천 도서 목록(reading_recommendations) 테이블 생성
CREATE TABLE IF NOT EXISTS public.reading_recommendations (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  slug TEXT NOT NULL UNIQUE DEFAULT 'default', -- 목록 식별자 (기본: 'default')
  title TEXT NOT NULL DEFAULT '추천 도서 목록',   -- 목록 제목
  content TEXT NOT NULL DEFAULT '',             -- Markdown 원문 (체크 항목은 '- [x] ...'로 저장)
  sort_order INTEGER NOT NULL DEFAULT 0,        -- 정렬 순서
  created_at TIMESTAMPTZ DEFAULT timezone('utc'::text, now()) NOT NULL,
  updated_at TIMESTAMPTZ DEFAULT timezone('utc'::text, now()) NOT NULL
);

-- 인덱스 생성
CREATE INDEX IF NOT EXISTS idx_reading_recommendations_slug
  ON public.reading_recommendations (slug);

-- 2. Row Level Security(RLS) 활성화
ALTER TABLE public.reading_recommendations ENABLE ROW LEVEL SECURITY;

-- 3. RLS 정책 설정
-- 1) 모든 사용자(익명 포함)가 추천 도서 목록을 조회(SELECT)할 수 있음 (백업 스크립트 및 열람 지원)
DROP POLICY IF EXISTS "Allow public read access on reading_recommendations" ON public.reading_recommendations;
CREATE POLICY "Allow public read access on reading_recommendations"
  ON public.reading_recommendations
  FOR SELECT
  USING (true);

-- 2) 로그인된(인증된) 사용자만 추천 도서 목록을 등록(INSERT)할 수 있음
DROP POLICY IF EXISTS "Allow authenticated insert on reading_recommendations" ON public.reading_recommendations;
CREATE POLICY "Allow authenticated insert on reading_recommendations"
  ON public.reading_recommendations
  FOR INSERT
  TO authenticated
  WITH CHECK (true);

-- 3) 로그인된(인증된) 사용자만 추천 도서 목록을 수정(UPDATE)할 수 있음
DROP POLICY IF EXISTS "Allow authenticated update on reading_recommendations" ON public.reading_recommendations;
CREATE POLICY "Allow authenticated update on reading_recommendations"
  ON public.reading_recommendations
  FOR UPDATE
  TO authenticated
  USING (true)
  WITH CHECK (true);

-- 4) 로그인된(인증된) 사용자만 추천 도서 목록을 삭제(DELETE)할 수 있음
DROP POLICY IF EXISTS "Allow authenticated delete on reading_recommendations" ON public.reading_recommendations;
CREATE POLICY "Allow authenticated delete on reading_recommendations"
  ON public.reading_recommendations
  FOR DELETE
  TO authenticated
  USING (true);

