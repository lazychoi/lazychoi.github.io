def update_hanja_txt_files(entries):
    grouped = {}
    for k, h, m in entries:
        fname = SYLLABLE_TO_FILE[k[0]]
        grouped.setdefault(fname, []).append((k, h, m))
    for fname in sorted(grouped.keys()):
        _update_single_txt_file(os.path.join(DATA_DIR, fname), grouped[fname])


def write_sql_script(entries, now_iso, sql_path=SQL_OUTPUT_PATH):
    lines = [
        "-- ============================================================",
        "-- 첨부 한자사전 25~35페이지([一部] 2획 下·万·丈·丌·扌·廾·上·𠀄 p.25~30, [一部] 3획 不 p.30~35) OCR 추출 데이터 일괄 반영 SQL",
        f"-- 총 {len(entries)}건",
        "-- Supabase Dashboard > SQL Editor에서 실행하면 즉시 DB에 반영됩니다.",
        "-- ============================================================",
        "",
        "INSERT INTO public.hanja_dict (hanja, korean, meaning, updated_at)",
        "VALUES",
    ]
    val_rows = [
        f"  ({sql_escape(h)}, {sql_escape(k)}, {sql_escape(m)}, {sql_escape(now_iso)}::timestamptz)"
        for k, h, m in entries
    ]
    lines.append(",\n".join(val_rows))
    lines.extend([
        "ON CONFLICT (hanja, korean)",
        "DO UPDATE SET",
        "  meaning = EXCLUDED.meaning,",
        "  updated_at = EXCLUDED.updated_at;",
        "",
    ])
    with open(sql_path, "w", encoding="utf-8", newline="\n") as fp:
        fp.write("\n".join(lines))
    print(f"[{os.path.basename(sql_path)}] Generated SQL script for {len(entries)} rows.")


