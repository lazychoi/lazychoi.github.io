def update_hanja_txt_files(entries):
    grouped = {}
    for k, h, m in entries:
        fname = SYLLABLE_TO_FILE[k[0]]
        grouped.setdefault(fname, []).append((k, h, m))

    for fname in sorted(grouped):
        fpath = os.path.join(DATA_DIR, fname)
        _update_single_txt_file(fpath, grouped[fname])


def write_sql_script(entries, now_iso, sql_path):
    """Write idempotent PostgreSQL UPSERT script for Supabase SQL Editor."""
    lines = [
        "-- Supabase SQL Editor script: Update Hanja dictionary meanings from OCR Pages 102 to 112",
        f"-- ([人部] 3~5획 他~伯: {len(entries)} entries)",
        f"-- Generated at {now_iso}",
        "",
        "begin;",
        "",
        "with v(hanja, korean, meaning, updated_at) as (",
        "  values",
    ]

    val_rows = []
    for k, h, m in entries:
        val_rows.append(
            f"    ({sql_escape(h)}, {sql_escape(k)}, {sql_escape(m)}, '{now_iso}'::timestamptz)"
        )
    lines.append(",\n".join(val_rows))
    lines.extend(
        [
            "),",
            "upd as (",
            "  update public.hanja_dict d",
            "     set meaning = v.meaning,",
            "         updated_at = v.updated_at",
            "    from v",
            "   where d.hanja = v.hanja",
            "     and d.korean = v.korean",
            "  returning d.hanja, d.korean",
            ")",
            "insert into public.hanja_dict (hanja, korean, meaning, created_at, updated_at)",
            "select v.hanja, v.korean, v.meaning, v.updated_at, v.updated_at",
            "  from v",
            " where not exists (",
            "   select 1 from public.hanja_dict d",
            "    where d.hanja = v.hanja and d.korean = v.korean",
            " );",
            "",
            "commit;",
            "",
        ]
    )

    with open(sql_path, "w", encoding="utf-8") as fp:
        fp.write("\n".join(lines))
    print(f"[{os.path.basename(sql_path)}] Generated SQL script for {len(entries)} rows.")


def main():
    now_iso = datetime.now(timezone.utc).strftime("%Y-%m-%dT%H:%M:%S.%fZ")

